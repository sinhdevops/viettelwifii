/* Extract public captured JSON only. Never evaluates the source bundle. */
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const ts = require("typescript");
const root = path.resolve(__dirname, "../..");
const assetMap = JSON.parse(
  fs.readFileSync(
    path.join(root, "src/generated/viettelup-assets.json"),
    "utf8",
  ),
);
const sourceUrl = Object.keys(assetMap).find((url) =>
  /\/goi-cuoc-roaming\/page-[^/]+\.js$/.test(url),
);
if (!sourceUrl) throw new Error("Captured roaming page bundle missing");
const bundlePath = path.join(root, "public", assetMap[sourceUrl]);
const source = fs.readFileSync(bundlePath, "utf8");
const tree = ts.createSourceFile(
  sourceUrl,
  source,
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.JS,
);
const candidates = [];
function visit(node) {
  if (
    ts.isCallExpression(node) &&
    node.expression.getText(tree) === "JSON.parse" &&
    node.arguments.length === 1 &&
    ts.isStringLiteral(node.arguments[0])
  ) {
    const value = JSON.parse(node.arguments[0].text);
    if (
      Array.isArray(value) &&
      value.length &&
      value.every(
        (row) =>
          typeof row.country_code === "string" &&
          typeof row.nameVN === "string",
      )
    )
      candidates.push(value);
  }
  ts.forEachChild(node, visit);
}
visit(tree);
if (candidates.length !== 1)
  throw new Error("Expected one unambiguous captured country array");
const countries = candidates[0];
for (const key of ["id", "country_code"]) {
  if (new Set(countries.map((row) => row[key])).size !== countries.length)
    throw new Error("Duplicate country " + key);
}
const hash = crypto.createHash("sha256").update(source).digest("hex");
const header =
  "// Generated by scripts/content/extract-roaming-countries.cjs from captured public JSON.\n" +
  "// Missing arrays remain missing; associations are source records, not a current eligibility guarantee.\n" +
  "export interface RoamingCountry {\n  readonly id: number;\n  readonly name: string;\n  readonly nameVN: string;\n  readonly country_code: string;\n  readonly flag: string;\n  readonly slug: string;\n  readonly suggest?: readonly string[];\n  readonly popular?: readonly string[];\n  readonly vip?: readonly string[];\n  readonly OTP: readonly string[];\n  readonly networks: string;\n}\n\n";
const helpers =
  "\n\n/** Original picker searches Vietnamese names by accent-insensitive prefix. */\n" +
  'export function normalizeCountrySearch(value: string): string {\n  return value.normalize("NFD").replace(/[\\u0300-\\u036f]/g, "").replace(/đ/g, "d").replace(/Đ/g, "D").toLowerCase();\n}\n\n' +
  "export function findRoamingCountries(query: string): readonly RoamingCountry[] {\n  const prefix = normalizeCountrySearch(query.trim());\n  return roamingCountries.filter(country => normalizeCountrySearch(country.nameVN).startsWith(prefix));\n}\n\n" +
  "/** Source router derives the destination from nameVN, not the JSON slug field. */\n" +
  'export function getRoamingCountrySourceUrl(country: RoamingCountry): string {\n  return "https://viettelwifii.vn/goi-cuoc-roaming/" + normalizeCountrySearch(country.nameVN).replaceAll(" ", "-");\n}\n';
const output =
  header +
  "export const roamingCountrySource = " +
  JSON.stringify(
    {
      url: sourceUrl,
      bundlePath: path.relative(root, bundlePath).replaceAll("\\", "/"),
      sha256: hash,
    },
    null,
    2,
  ) +
  " as const;\n\n" +
  "export const roamingCountries: readonly RoamingCountry[] = " +
  JSON.stringify(countries, null, 2) +
  ";" +
  helpers +
  '\n\n/** Offline flag fallback using captured flag codes; no remote assets requested. */\nexport function getCountryFlagEmoji(flag: string): string {\n  if (/^GB-(ENG|SCT|WLS)$/.test(flag)) {\n    return "\\u{1F3F4}" + Array.from(flag.toLowerCase().replace("-", ""), char => String.fromCodePoint(0xE0000 + char.charCodeAt(0))).join("") + "\\u{E007F}";\n  }\n  if (!/^[A-Z]{2}$/.test(flag)) return "🌐";\n  // Unsupported source codes have no standard Unicode flag. Keep a neutral icon.\n  if (["KS", "HA"].includes(flag)) return "🌐";\n  return Array.from(flag, char => String.fromCodePoint(0x1F1E6 + char.charCodeAt(0) - 65)).join("");\n}\n';
fs.writeFileSync(
  path.join(root, "src/features/collections/roaming-country-data.ts"),
  output,
);
const reportPath = path.join(
  root,
  "reports/agent-handoffs/vt_forms_integrations/COLLECTION-COUNTRY-02-extraction.json",
);
fs.mkdirSync(path.dirname(reportPath), { recursive: true });
fs.writeFileSync(
  reportPath,
  JSON.stringify(
    {
      sourceUrl,
      bundlePath: path.relative(root, bundlePath),
      sha256: hash,
      countries: countries.length,
      associations: Object.fromEntries(
        ["suggest", "popular", "vip", "OTP"].map((key) => [
          key,
          countries.reduce((n, c) => n + (c[key]?.length || 0), 0),
        ]),
      ),
      originalSelection:
        'router.push("/goi-cuoc-roaming/" + normalize(nameVN).replaceAll(" ", "-")) after 800ms',
      originalSearch: "accent-insensitive nameVN prefix",
      execution:
        "TypeScript AST literal extraction only; no source JavaScript executed",
    },
    null,
    2,
  ) + "\n",
);
console.log("Extracted " + countries.length + " source country records");

#!/usr/bin/env node
/**
 * Codemod: move price-comparison tables that are copied verbatim into several
 * package pages into shared components under src/content/packages/price-tables/.
 *
 * A table block is a top-level child of the Details root starting with
 *   <div className="flex justify-start overflow-x-auto ...">
 * Its register buttons carry itemPath="<page route>", which becomes the
 * `itemPath` prop, so rendered markup stays identical.
 *
 * Usage: node scripts/packages/extract-shared-price-tables.mjs [--dry-run]
 * Idempotent: running again after extraction finds no duplicated tables.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = "src/content/packages";
const outDir = path.join(dir, "price-tables");
const dryRun = process.argv.includes("--dry-run");
const tableStart = '      <div className="flex justify-start overflow-x-auto';

function routeFor(file) {
  const code = file.replace(/^(general|postpaid)-|\.tsx$/g, "");
  return `${file.startsWith("postpaid-") ? "/goi-cuoc-viettel/tra-sau/" : "/goi-cuoc-viettel/"}${code}`;
}

const files = readdirSync(dir).filter((f) =>
  /^(general|postpaid)-.+\.tsx$/.test(f),
);
const sources = new Map(
  files.map((f) => [
    f,
    readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n"),
  ]),
);

/** Collect [start, end) line ranges of table blocks with their normalized text. */
function tableBlocks(src, route) {
  const lines = src.split("\n");
  const blocks = [];
  for (let i = 0; i < lines.length; i++) {
    if (!lines[i].startsWith(tableStart)) continue;
    let j = i + 1;
    while (j < lines.length && !/^      <\/div>/.test(lines[j])) j++;
    const raw = lines.slice(i, j + 1).join("\n");
    const paths = new Set(
      [...raw.matchAll(/itemPath="([^"]*)"/g)].map((m) => m[1]),
    );
    if ([...paths].some((p) => p !== route))
      throw new Error(`Table with foreign itemPath in ${route}`);
    blocks.push({
      start: i,
      end: j + 1,
      normalized: raw.replaceAll(`itemPath="${route}"`, "itemPath={itemPath}"),
    });
    i = j;
  }
  return blocks;
}

const groups = new Map(); // normalized -> { files: [], name }
const perFile = new Map();
for (const [file, src] of sources) {
  const blocks = tableBlocks(src, routeFor(file));
  perFile.set(file, blocks);
  for (const block of blocks) {
    const group = groups.get(block.normalized) ?? { files: [] };
    group.files.push(file);
    groups.set(block.normalized, group);
  }
}

const shared = [...groups.entries()].filter(([, g]) => g.files.length > 1);
const usedNames = new Set();
for (const [normalized, group] of shared) {
  // Name by the first package code listed in the table.
  const firstCell =
    normalized.match(/<td[\s\S]*?<p[^>]*>([\s\S]*?)<\/p>/)?.[1] ?? "";
  const firstCode =
    firstCell
      .replace(/<[^>]*>/g, " ")
      .replace(/\{"\s*"\}/g, " ")
      .trim()
      .split(/\s+/)[0] || "Shared";
  let name = `PriceTable${firstCode.replace(/[^A-Za-z0-9]/g, "")}`;
  if (!/^PriceTable[A-Za-z0-9]/.test(name)) name = "PriceTableShared";
  let unique = name;
  for (let n = 2; usedNames.has(unique); n++) unique = `${name}V${n}`;
  usedNames.add(unique);
  group.name = unique;
  group.file = unique.replace(/^PriceTable/, "price-table-").toLowerCase();
}

function importsFor(body) {
  const imports = [];
  if (body.includes("PackageSourceDialogTrigger"))
    imports.push(
      'import { PackageSourceDialogTrigger } from "@/components/packages/package-source-dialog-trigger";',
    );
  if (body.includes("sourceAsset("))
    imports.push(
      'import { sourceAsset } from "@/lib/viettelup-source-assets";',
    );
  if (body.includes("siteConfig"))
    imports.push('import { siteConfig } from "@/lib/site-config";');
  if (/<Link\b/.test(body)) imports.push('import Link from "next/link";');
  return imports;
}

if (!dryRun) mkdirSync(outDir, { recursive: true });
for (const [normalized, group] of shared) {
  const codes = group.files.map((f) => routeFor(f).split("/").at(-1));
  const body = normalized
    .split("\n")
    .map((line) => line.replace(/^  /, ""))
    .join("\n");
  const content = [
    `/* Shared price table, rendered by ${group.files.length} package pages: ${codes.join(", ")}.`,
    "   Edit it once here. Generated by scripts/packages/extract-shared-price-tables.mjs. */",
    ...(body.includes("<img")
      ? ["/* eslint-disable @next/next/no-img-element */"]
      : []),
    ...importsFor(body),
    "",
    `export function ${group.name}({ itemPath }: { itemPath: string }) {`,
    "  return (",
    body,
    "  );",
    "}",
    "",
  ].join("\n");
  if (!dryRun) writeFileSync(path.join(outDir, `${group.file}.tsx`), content);
}

let replaced = 0;
for (const [file, src] of sources) {
  const route = routeFor(file);
  const lines = src.split("\n");
  const used = new Set();
  // Replace bottom-up so earlier line indexes stay valid.
  for (const block of [...perFile.get(file)].reverse()) {
    const group = groups.get(block.normalized);
    if (!group?.name) continue;
    lines.splice(
      block.start,
      block.end - block.start,
      `      <${group.name} itemPath="${route}" />`,
    );
    used.add(group);
    replaced++;
  }
  if (!used.size) continue;
  let out = lines.join("\n");
  const newImports = [...used]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((g) => `import { ${g.name} } from "./price-tables/${g.file}";`);
  // Insert after the last import line.
  const outLines = out.split("\n");
  let lastImport = -1;
  outLines.forEach((line, i) => {
    if (/^import .* from ".*";$/.test(line)) lastImport = i;
  });
  outLines.splice(lastImport + 1, 0, ...newImports);
  out = outLines.join("\n");
  // Drop imports the remaining page body no longer uses.
  const bodyStart = out.indexOf("export default function");
  const body = out.slice(bodyStart);
  const dropIfUnused = [
    [
      "PackageSourceDialogTrigger",
      /^import \{ PackageSourceDialogTrigger \} from ".*";\n/m,
    ],
    ["sourceAsset", /^import \{ sourceAsset \} from ".*";\n/m],
    ["siteConfig", /^import \{ siteConfig \} from ".*";\n/m],
  ];
  for (const [identifier, pattern] of dropIfUnused)
    if (!body.includes(identifier)) out = out.replace(pattern, "");
  if (!body.includes("<img"))
    out = out.replace(
      /^\/\* eslint-disable @next\/next\/no-img-element \*\/\n/m,
      "",
    );
  if (!dryRun) writeFileSync(path.join(dir, file), out);
}

const before = [...sources.values()].reduce((s, t) => s + t.length, 0);
console.log(
  `${shared.length} shared tables, ${replaced} table copies replaced in ${files.length} files` +
    (dryRun ? " (dry run)" : ""),
);
console.log(`package sources before: ${(before / 1e6).toFixed(2)}MB`);
